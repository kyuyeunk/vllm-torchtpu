"""Fails when `TPUModelRunner` gains a new attribute set outside `__init__`.

A step stage that stores a result on `self` for a later stage to read hands
the value over through a side channel: the reader cannot see who wrote it, or
whether it was written this step. Stages should return values instead.

This is a ratchet. `runner_side_channels_baseline.txt` lists the attribute
names already assigned outside `__init__`. A new name fails, and a listed name
that is no longer assigned outside `__init__` fails until it is removed, so
the list only shrinks. Reads only the source with `ast`; imports nothing from
the package. To rewrite the baseline:

    python3 tests/runner/test_runner_side_channels.py --update
"""

import argparse
import ast
import pathlib
import sys

import pytest

_REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
_RUNNER = _REPO_ROOT / "src" / "vllm_torchtpu" / "runner" / "tpu_runner.py"
_BASELINE = pathlib.Path(__file__).with_name("runner_side_channels_baseline.txt")
_CLASS = "TPUModelRunner"


def _self_store(node: ast.AST) -> str | None:
    """Returns the attribute name if `node` rebinds an attribute of `self`.

    Covers `self.x = v`, `self.x += v`, `self.x: T = v`, tuple targets and
    `setattr(self, "x", v)`. `self.x[i] = v` mutates the object `self.x`
    already holds and is not counted.

    Args:
        node: Any AST node.

    Returns:
        The attribute name, `<dynamic>` for `setattr` with a non-literal name,
        or None.
    """
    if (
        isinstance(node, ast.Attribute)
        and isinstance(node.ctx, ast.Store)
        and isinstance(node.value, ast.Name)
        and node.value.id == "self"
    ):
        return node.attr
    if (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id == "setattr"
        and len(node.args) >= 2
        and isinstance(node.args[0], ast.Name)
        and node.args[0].id == "self"
    ):
        name = node.args[1]
        if isinstance(name, ast.Constant) and isinstance(name.value, str):
            return name.value
        return "<dynamic>"
    return None


def find_side_channel_stores(source: str, class_name: str) -> list[tuple[int, str]]:
    """Returns `(lineno, attr)` for stores on `self` outside `__init__`.

    Args:
        source: Python source containing the class.
        class_name: The class to scan.

    Returns:
        One entry per store, in source order, from every method except
        `__init__`, including functions nested in those methods.

    Raises:
        LookupError: If `source` has no top-level class `class_name`.
    """
    tree = ast.parse(source)
    cls = next(
        (n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == class_name),
        None,
    )
    if cls is None:
        raise LookupError(f"no top-level class {class_name}")
    stores: list[tuple[int, str]] = []
    for method in cls.body:
        if not isinstance(method, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        if method.name == "__init__":
            continue
        for node in ast.walk(method):
            # Every store `_self_store` matches is an expression node.
            if not isinstance(node, ast.expr):
                continue
            attr = _self_store(node)
            if attr is not None:
                stores.append((node.lineno, attr))
    return sorted(stores)


def _load_baseline() -> set[str]:
    """Returns the baseline attribute names, without comments."""
    return {
        line.strip()
        for line in _BASELINE.read_text().splitlines()
        if line.strip() and not line.startswith("#")
    }


def _write_baseline(attrs: set[str]) -> None:
    """Rewrites the baseline file.

    Args:
        attrs: Attribute names assigned outside `__init__`.
    """
    header = (
        f"# Attributes {_CLASS} assigns outside __init__, as of the last update.\n"
        "# Generated by tests/runner/test_runner_side_channels.py --update.\n"
        "# Shrink this file by returning the value from the stage; never grow it.\n"
    )
    _ = _BASELINE.write_text(header + "".join(f"{a}\n" for a in sorted(attrs)))


def test_runner_gains_no_new_side_channel() -> None:
    stores = find_side_channel_stores(_RUNNER.read_text(), _CLASS)
    new = sorted({(line, a) for line, a in stores if a not in _load_baseline()})
    assert not new, (
        f"{_CLASS} assigns new attributes outside __init__:\n  "
        + "\n  ".join(f"tpu_runner.py:{line}: self.{a}" for line, a in new)
        + "\nReturn the value from the stage that computes it and pass it to "
        "the stage that reads it. A per-instance setting belongs in __init__."
    )


def test_runner_side_channel_baseline_has_no_stale_entries() -> None:
    found = {a for _, a in find_side_channel_stores(_RUNNER.read_text(), _CLASS)}
    stale = sorted(_load_baseline() - found)
    assert not stale, (
        f"No longer assigned outside {_CLASS}.__init__ (nice): {stale}\n"
        "Run `python3 tests/runner/test_runner_side_channels.py --update` "
        "and commit the baseline."
    )


_WRAP = "class R:\n    def __init__(self):\n        self.a = 0\n{}"


@pytest.mark.parametrize(
    "body",
    [
        pytest.param("", id="init_only"),
        pytest.param("    def f(self):\n        self.a[0] = 1\n", id="subscript"),
        pytest.param("    def f(self):\n        x = self.a\n", id="read"),
        pytest.param("    def f(self, o):\n        o.a = 1\n", id="other_object"),
    ],
)
def test_allows(body: str) -> None:
    assert find_side_channel_stores(_WRAP.format(body), "R") == []


@pytest.mark.parametrize(
    ("body", "attr"),
    [
        pytest.param("    def f(self):\n        self.b = 1\n", "b", id="assign"),
        pytest.param("    def f(self):\n        self.b += 1\n", "b", id="augassign"),
        pytest.param(
            "    def f(self):\n        self.b: int = 1\n", "b", id="annotated"
        ),
        pytest.param("    def f(self):\n        _, self.b = 1, 2\n", "b", id="tuple"),
        pytest.param(
            "    def f(self):\n        def g():\n            self.b = 1\n",
            "b",
            id="nested_function",
        ),
        pytest.param(
            "    async def f(self):\n        self.b = 1\n", "b", id="async_method"
        ),
        pytest.param(
            "    def f(self):\n        setattr(self, 'b', 1)\n", "b", id="setattr"
        ),
        pytest.param(
            "    def f(self, n):\n        setattr(self, n, 1)\n",
            "<dynamic>",
            id="setattr_dynamic",
        ),
    ],
)
def test_rejects(body: str, attr: str) -> None:
    assert [a for _, a in find_side_channel_stores(_WRAP.format(body), "R")] == [attr]


def _main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--update", action="store_true", required=True)
    _ = parser.parse_args()
    found = {a for _, a in find_side_channel_stores(_RUNNER.read_text(), _CLASS)}
    _write_baseline(found)
    print(f"baseline updated: {len(found)} attributes")
    return 0


if __name__ == "__main__":
    sys.exit(_main())
