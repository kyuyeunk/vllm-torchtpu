"""Fail when a file gains a finding from the repo's semgrep rules.

The rules live in ``tools/semgrep/``. Today that is ``restated-vmem-rule``:
an integer literal in a size compared with ``vmem_capacity_bytes``, which
restates a kernel's admission rule instead of calling it.

This is a ratchet in the style of ``check_b023_baseline.py``.
``tools/semgrep_baseline.txt`` records the findings per file and rule, a file
that gains one fails, and a file that loses one fails until the baseline is
shrunk. Counts, not line numbers, so an unrelated edit that moves a finding
does not fail the hook. Run semgrep directly to see the sites:

    semgrep scan --metrics=off --config tools/semgrep src

Run directly to see the current state:

    tools/check_semgrep_baseline.py            # check
    tools/check_semgrep_baseline.py --update   # rewrite the baseline
"""

from __future__ import annotations

import argparse
import collections
import json
import pathlib
import subprocess
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
BASELINE_PATH = REPO_ROOT / "tools" / "semgrep_baseline.txt"
RULES = "tools/semgrep"
TARGET = "src/vllm_torchtpu"


def count_findings() -> dict[str, int]:
    """Returns findings keyed by ``relpath:rule``.

    Raises:
        RuntimeError: If semgrep could not run.
    """
    result = subprocess.run(
        [
            "semgrep",
            "scan",
            "--metrics=off",
            "--disable-version-check",
            "--quiet",
            "--json",
            "--config",
            RULES,
            TARGET,
        ],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    # Without --error, semgrep exits 0 whether or not it found anything.
    if result.returncode != 0:
        raise RuntimeError(f"semgrep exited {result.returncode}:\n{result.stderr}")

    counts: collections.Counter[str] = collections.Counter()
    for finding in json.loads(result.stdout)["results"]:
        # `check_id` is prefixed with the rule file's directory.
        rule = finding["check_id"].rpartition(".")[2]
        counts[f"{finding['path']}:{rule}"] += 1
    return dict(counts)


def load_baseline() -> dict[str, int]:
    """Returns the baseline counts, without comments."""
    counts: dict[str, int] = {}
    for raw in BASELINE_PATH.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        key, _, count = line.rpartition(" ")
        counts[key] = int(count)
    return counts


def write_baseline(counts: dict[str, int]) -> None:
    """Rewrites the baseline file.

    Args:
        counts: Findings keyed by ``relpath:rule``.
    """
    header = (
        "# semgrep findings per file and rule, as of the last update.\n"
        "# Generated by tools/check_semgrep_baseline.py --update.\n"
        "# Shrink this file by calling the kernel's predicate; never grow it.\n"
    )
    body = "".join(f"{key} {counts[key]}\n" for key in sorted(counts))
    _ = BASELINE_PATH.write_text(header + body)


def main() -> int:
    """Checks the tree against the baseline.

    Returns:
        0 when the tree matches the baseline, 1 otherwise.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument(
        "--update",
        action="store_true",
        help="rewrite the baseline from the current tree",
    )
    # pre-commit passes the staged filenames; this hook always scans the
    # whole package, so accept and ignore them.
    _ = parser.add_argument("filenames", nargs="*", help=argparse.SUPPRESS)
    args = parser.parse_args()

    found = count_findings()
    if args.update:
        write_baseline(found)
        print(f"baseline updated: {sum(found.values())} findings in {len(found)} files")
        return 0

    baseline = load_baseline()
    grew = sorted(key for key, n in found.items() if n > baseline.get(key, 0))
    shrank = sorted(key for key, n in baseline.items() if found.get(key, 0) < n)

    if grew:
        print("These files gained a semgrep finding:\n")
        for key in grew:
            print(f"  {key}  {baseline.get(key, 0)} -> {found[key]}")
        print(
            "\nRun `semgrep scan --config tools/semgrep src` to see the "
            "sites. Call the kernel's admission predicate instead of "
            "restating its arithmetic."
        )
        return 1

    if shrank:
        print("These files have fewer semgrep findings than the baseline (nice):\n")
        for key in shrank:
            print(f"  {key}  {baseline[key]} -> {found.get(key, 0)}")
        print(
            "\nRun `tools/check_semgrep_baseline.py --update` to shrink the "
            "baseline, and commit it."
        )
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
